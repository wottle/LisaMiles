#!/usr/bin/env python3
"""Build the {T202}icon file for the 1000 Miles tool, and the Workshop program that writes it.

The Lisa takes text over serial, not binary, so the icon travels as hex inside a small Pascal
program (src/MILES-MKICON.TEXT) which writes the real file on the Lisa.

File layout (814 bytes, read from the Minesweeper icon file):
  26 bytes  header   (48 x 32 pixels, copied unchanged)
  32 rows x 24 bytes, each row four 6-byte (48-pixel) planes:
      +0  click area   (here: the same as the mask)
      +6  mask         (1 = opaque, the silhouette)
      +12 image        (1 = black)
      +18 checkerboard (aa on even rows, 55 on odd rows, copied unchanged)
  20 bytes  trailer  (copied unchanged)

  python3 tools/gen_toolicon.py        writes src/MILES-MKICON.TEXT, src/MILES-ICONMK.TEXT and a preview
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "mockups"))
import icon_options as io  # noqa: E402

W, H = 48, 32
HEADER = bytes.fromhex("0003000000020030" "0000ffe000300020" "018a000000200000" "000c")
TRAILER = bytes.fromhex("0000003000600090" "00c0003000300030" "0030ffff")
ICON_NAME = "{T202}icon"
BYTES_PER_LINE = 16


def rows_to_bytes(img, invert):
    """One list of six bytes per pixel row.  invert=True: bit set where the PIL pixel is black."""
    px = img.load()
    rows = []
    for y in range(H):
        row = bytearray(6)
        for x in range(W):
            on = (px[x, y] == 0) if invert else bool(px[x, y])
            if on:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return rows


def gauge_planes():
    """(image rows, mask rows) for the chosen icon, option E, the gauge."""
    img = io.option_e()
    image = rows_to_bytes(img, invert=True)
    mask = rows_to_bytes(io.silhouette(img), invert=False)
    return image, mask


def build_icon():
    image, mask = gauge_planes()
    out = bytearray(HEADER)
    for r in range(H):
        out += mask[r]                                   # click area
        out += mask[r]                                   # mask
        out += image[r]                                  # image
        out += bytes([0xAA if r % 2 == 0 else 0x55]) * 6  # checkerboard
    out += TRAILER
    assert len(out) == 814
    return bytes(out)


PASCAL_HEAD = """\
{ MILES-MKICON.TEXT -- writes the icon file for tool 202 (1000 Miles).  Generated by            }
{ tools/gen_toolicon.py: do not edit by hand.  The Lisa receives text over serial, not binary,   }
{ so the icon (814 bytes) is held below as hex words and written out here.  Run it, then run     }
{ MILES/MAKE so InstallTool picks the icon up.                                                   }
PROGRAM MkIcon;

USES (*$U SysCall.obj *) SysCall;

CONST
   fileBytes = 814;

TYPE
   hexText = string[63];

VAR
   ecode  : integer;
   ref    : integer;
   actual : longint;
   path   : pathname;
   buf    : array [0..406] of integer;

FUNCTION HexVal (c : char) : integer;
BEGIN
   IF (c >= '0') AND (c <= '9') THEN HexVal := ord(c) - 48
   ELSE HexVal := ord(c) - 55
END;

{ Words from hex text, four digits each, into buf starting at word number first. }
PROCEDURE Put (first : integer; s : hexText);
VAR k, j : integer;
    w    : longint;
BEGIN
   FOR k := 0 TO (length(s) DIV 4) - 1 DO BEGIN
      w := 0;
      FOR j := 1 TO 4 DO
         w := w * 16 + HexVal(s[k * 4 + j]);
      IF w > 32767 THEN w := w - 65536;
      buf[first + k] := w
   END
END;

PROCEDURE Fill;
BEGIN
"""

PASCAL_TAIL = """\
END;

BEGIN
   Fill;
   path := '%s';
   kill_object(ecode, path);
   make_file(ecode, path, 0);
   IF ecode > 0 THEN writeln('Could not create ', path, ', error ', ecode)
   ELSE BEGIN
      open(ecode, path, ref, [DWrite]);
      IF ecode > 0 THEN writeln('Could not open ', path, ', error ', ecode)
      ELSE BEGIN
         write_data(ecode, ref, ord4(@buf), fileBytes, actual, Absolute, 0);
         close_object(ecode, ref);
         IF ecode > 0 THEN writeln('Write failed, error ', ecode)
         ELSE writeln('Wrote ', actual, ' bytes to ', path)
      END
   END
END.
"""


def pascal_program(data):
    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE].hex().upper()
        lines.append("   Put(%d, '%s');" % (i // 2, chunk))
    lines[-1] = lines[-1][:-1]                      # no semicolon before END
    return PASCAL_HEAD + "\n".join(lines) + "\n" + PASCAL_TAIL % ICON_NAME


EXEC = """\
$EXEC
P{ascal}MILES/MKICON


L{ink}MILES/MKICON
IOSPASLIB


MILES/MKICON

R{un}MILES/MKICON
$ENDEXEC
"""


def main():
    root = os.path.abspath(os.path.join(HERE, ".."))
    data = build_icon()
    with open(os.path.join(root, "src", "MILES-MKICON.TEXT"), "w") as f:
        f.write(pascal_program(data))
    with open(os.path.join(root, "src", "MILES-ICONMK.TEXT"), "w") as f:
        f.write(EXEC)
    # preview of what will be on the desktop: the image through its mask
    from PIL import Image
    image, mask = gauge_planes()
    prev = Image.new("L", (W, H), 210)
    pp = prev.load()
    for y in range(H):
        for x in range(W):
            bit = 0x80 >> (x % 8)
            if mask[y][x // 8] & bit:
                pp[x, y] = 0 if image[y][x // 8] & bit else 255
    big = prev.resize((W * 6, H * 9), Image.NEAREST)
    big.save(os.path.join(root, "docs", "mockups", "tool_icon_preview.png"))
    print("wrote MILES-MKICON.TEXT (%d bytes of icon), MILES-ICONMK.TEXT, preview" % len(data))


if __name__ == "__main__":
    main()
