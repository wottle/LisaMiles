#!/usr/bin/env python3
"""Build the {T202}icon file for the 1000 Miles tool, and the Workshop program that writes it.

The Lisa takes text over serial, not binary, so the icon travels as hex inside a small Pascal
program (src/MILES-MKICON.TEXT) which writes the real file on the Lisa.

File layout (814 bytes, read from the Minesweeper icon file):
  26 bytes  header   (48 x 32 pixels, copied unchanged)
  32 rows x 24 bytes, each row four 6-byte (48-pixel) planes:
      +0  click area   (the gauge silhouette)
      +6  picture      (1 = black; drawn on a white box)
      +12 overlay      (1 = drawn white on top while the icon is selected)
      +18 checkerboard (aa on even rows, 55 on odd rows, copied unchanged)
  20 bytes  trailer  (copied unchanged)

  python3 tools/gen_toolicon.py        writes src/MILES-MKICON.TEXT and a preview
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "mockups"))
import icon_options as io  # noqa: E402

W, H = 48, 32
SOLID_AREA = True   # click/erase area is the whole box, not the silhouette (silhouette left pixels behind when moved)
HEADER = bytes.fromhex("0003000000020030" "0000ffe000300020" "018a000000200000" "000c")
TRAILER = bytes.fromhex("0000003000600090" "00c0003000300030" "0030ffff")
ICON_NAME = "{T202}icon"
BYTES_PER_LINE = 16


def rows_to_bytes(img, invert):
    """One list of six bytes per pixel row.  invert=True: bit set where the PIL pixel is black."""
    px = img.load()
    rows = []
    for y in range(H):
        row = bytearray(6)
        for x in range(W):
            on = (px[x, y] == 0) if invert else bool(px[x, y])
            if on:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return rows


def _bits(img, black):
    """Set of (x, y) for the pixels of a PIL 1-bit image that are black (or white)."""
    px = img.load()
    return {(x, y) for y in range(H) for x in range(W) if (px[x, y] == 0) == black}


def _erode(cells, n):
    for _ in range(n):
        cells = {(x, y) for (x, y) in cells
                 if {(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)} <= cells}
    return cells


def _to_rows(cells):
    rows = [bytearray(6) for _ in range(H)]
    for x, y in cells:
        rows[y][x // 8] |= 0x80 >> (x % 8)
    return [bytes(r) for r in rows]


def gauge_planes():
    """(picture, overlay, area) rows for the chosen icon, option E, the gauge.

    What the Office System does with them (found with a probe icon):
      picture  drawn black, on a white box           -> a dark gauge face, markings left light, black 1000
      overlay  drawn white on top when selected      -> a thin ring just inside the face
      area     click area                            -> the gauge silhouette
    """
    body = io.option_e(digits=False)
    whole = io.option_e(digits=True)
    mask = io.silhouette(body).load()
    face = {(x, y) for y in range(H) for x in range(W) if mask[x, y]}
    strokes = _bits(body, True)
    digits = _bits(whole, True) - strokes
    picture = (face - strokes) | digits
    overlay = _erode(face, 2) - _erode(face, 3)
    return _to_rows(picture), _to_rows(overlay), _to_rows(face)


def build_icon():
    picture, overlay, area = gauge_planes()
    out = bytearray(HEADER)
    if SOLID_AREA:
        area = [b'\xff' * 6] * H                      # whole 48 x 32 box: the Office System erases it all on a move
    for r in range(H):
        out += area[r]                                   # click area
        out += picture[r]                                # picture (black)
        out += overlay[r]                                # overlay (white when selected)
        out += bytes([0xAA if r % 2 == 0 else 0x55]) * 6  # checkerboard
    out += TRAILER
    assert len(out) == 814
    return bytes(out)


PASCAL_HEAD = """\
{ MILES-MKICON.TEXT -- writes the icon file for tool 202 (1000 Miles).  Generated by            }
{ tools/gen_toolicon.py: do not edit by hand.  The Lisa receives text over serial, not binary,   }
{ so the icon (814 bytes) is held below as hex words and written out here.  Run it, then run     }
{ MILES/MAKE so InstallTool picks the icon up.                                                   }
PROGRAM MkIcon;

USES (*$U SysCall.obj *) SysCall;

CONST
   fileBytes = 814;

TYPE
   hexText = string[63];

VAR
   ecode  : integer;
   ref    : integer;
   actual : longint;
   path   : pathname;
   buf    : array [0..406] of integer;

FUNCTION HexVal (c : char) : integer;
BEGIN
   IF (c >= '0') AND (c <= '9') THEN HexVal := ord(c) - 48
   ELSE HexVal := ord(c) - 55
END;

{ Words from hex text, four digits each, into buf starting at word number first. }
PROCEDURE Put (first : integer; s : hexText);
VAR k, j : integer;
    w    : longint;
BEGIN
   FOR k := 0 TO (length(s) DIV 4) - 1 DO BEGIN
      w := 0;
      FOR j := 1 TO 4 DO
         w := w * 16 + HexVal(s[k * 4 + j]);
      IF w > 32767 THEN w := w - 65536;
      buf[first + k] := w
   END
END;

PROCEDURE Fill;
BEGIN
"""

PASCAL_TAIL = """\
END;

BEGIN
   Fill;
   path := '%s';
   kill_object(ecode, path);
   make_file(ecode, path, 0);
   IF ecode > 0 THEN writeln('Could not create ', path, ', error ', ecode)
   ELSE BEGIN
      open(ecode, path, ref, [DWrite]);
      IF ecode > 0 THEN writeln('Could not open ', path, ', error ', ecode)
      ELSE BEGIN
         write_data(ecode, ref, ord4(@buf), fileBytes, actual, Absolute, 0);
         close_object(ecode, ref);
         IF ecode > 0 THEN writeln('Write failed, error ', ecode)
         ELSE writeln('Wrote ', actual, ' bytes to ', path)
      END
   END
END.
"""


def pascal_program(data):
    lines = []
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE].hex().upper()
        lines.append("   Put(%d, '%s');" % (i // 2, chunk))
    lines[-1] = lines[-1][:-1]                      # no semicolon before END
    return PASCAL_HEAD + "\n".join(lines) + "\n" + PASCAL_TAIL % ICON_NAME


def letter_rows(ch):
    """A big solid letter, 48x32, as six-byte rows: used by --probe to learn what each plane does."""
    from PIL import Image, ImageDraw, ImageFont
    img = Image.new("1", (W, H), 1)
    font = ImageFont.truetype("/System/Library/Fonts/Helvetica.ttc", 34)
    d = ImageDraw.Draw(img)
    box = d.textbbox((0, 0), ch, font=font)
    d.text(((W - (box[2] - box[0])) // 2 - box[0], (H - (box[3] - box[1])) // 2 - box[1] - 1), ch, font=font, fill=0)
    return rows_to_bytes(img, invert=True)


def build_probe():
    a, b, c = letter_rows("A"), letter_rows("B"), letter_rows("C")
    out = bytearray(HEADER)
    for r in range(H):
        out += a[r] + b[r] + c[r] + bytes([0xAA if r % 2 == 0 else 0x55]) * 6
    out += TRAILER
    return bytes(out)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--probe":
        os.makedirs(sys.argv[2], exist_ok=True)
        with open(os.path.join(sys.argv[2], "MILES-MKICON.TEXT"), "w") as f:
            f.write(pascal_program(build_probe()))
        print("wrote probe MKICON to", sys.argv[2])
        return
    root = os.path.abspath(os.path.join(HERE, ".."))
    data = build_icon()
    with open(os.path.join(root, "src", "MILES-MKICON.TEXT"), "w") as f:
        f.write(pascal_program(data))
    # preview: the icon unselected and selected, with the Lisa's tall pixels
    from PIL import Image
    picture, overlay, _ = gauge_planes()

    def cell(rows, x, y):
        return bool(rows[y][x // 8] & (0x80 >> (x % 8)))

    sheet = Image.new("L", (2 * (W + 4) * 6, (H + 4) * 9), 200)
    for k, selected in enumerate((False, True)):
        tile = Image.new("L", (W, H), 255)
        tp = tile.load()
        for y in range(H):
            for x in range(W):
                if cell(picture, x, y):
                    tp[x, y] = 0
                if selected and cell(overlay, x, y):
                    tp[x, y] = 255
        big = tile.resize((W * 6, H * 9), Image.NEAREST)
        sheet.paste(big, (k * (W + 4) * 6 + 12, 18))
    sheet.save(os.path.join(root, "docs", "mockups", "tool_icon_preview.png"))
    print("wrote MILES-MKICON.TEXT (%d bytes of icon) and the preview" % len(data))


if __name__ == "__main__":
    main()
